#!/bin/bash

update_kernel_elf_doc() {

    export SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &>/dev/null && pwd)
    echo $SCRIPT_DIR
    pushd $SCRIPT_DIR > /dev/null

        local -r path_="./docs/notes/001_current_state_of_kernel_ELF.md"

        echo "<!-- This document is autogenerated! See \`build_kernel_and_run.sh\` -->" > $path_
        echo "" >> $path_

        echo "# Kernel ELF" >> $path_
        echo "" >> $path_

        echo "## stat" >> $path_
        echo "" >> $path_

        echo "\`$ stat kernel\`" >> $path_
        echo "" >> $path_

        echo "\`\`\`text" >> $path_
        stat kernel >> $path_
        echo "\`\`\`" >> $path_

        echo "## readelf" >> $path_
        echo "" >> $path_

        echo "\`$ readelf -hlSW kernel\`" >> $path_
        echo "" >> $path_

        echo "\`\`\`text" >> $path_
        readelf -hlSW kernel >> $path_
        echo "\`\`\`" >> $path_

    popd > /dev/null
}
