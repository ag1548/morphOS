#!/bin/bash

append_comment_header() {
    echo "<!-- This document is autogenerated! See \`build_kernel_and_run.sh\` -->" >> $1
    echo "" >> $1
}

append_title() {
    echo "# Kernel ELF" >> $1
    echo "" >> $1
}

append_stat_output() {
    echo "## stat" >> $1
    echo "" >> $1

    echo "\`$ stat kernel\`" >> $1
    echo "" >> $1

    echo "\`\`\`text" >> $1
    stat kernel >> $1
    echo "\`\`\`" >> $1
}

append_readelf_output() {
    echo "## readelf" >> $1
    echo "" >> $1

    echo "\`$ readelf -hlSW kernel\`" >> $1
    echo "" >> $1

    echo "\`\`\`text" >> $1
    readelf -hlSW kernel >> $1
    echo "\`\`\`" >> $1
}

append_nm_output() {
    echo "## nm -n kernel" >> $1
    echo "" >> $1

    echo "\`\`\`text" >> $1
    nm -n kernel >> $1
    echo "\`\`\`" >> $1
}

update_kernel_elf_doc() {

    export SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &>/dev/null && pwd)
    # echo $SCRIPT_DIR
    pushd $SCRIPT_DIR > /dev/null

        local -r path_="./docs/notes/001_current_state_of_kernel_ELF.md"
        echo -n "" > $path_

        append_comment_header $path_

        append_title $path_

        append_stat_output $path_

        append_readelf_output $path_

        append_nm_output $path_

    popd > /dev/null
}
